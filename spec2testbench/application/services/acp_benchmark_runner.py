"""Deterministic AnalogCoder-Pro ACP-28 benchmark runner.

This runner deliberately disables the LLM. Its scientific question is the
quality/compliance of the DUTs generated by AnalogCoder-Pro, not the quality of
Spec2Testbench's LLM planner. LLM experiments belong to a separate campaign.
"""
from __future__ import annotations

import csv
import hashlib
import json
from collections import defaultdict
from dataclasses import asdict
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

from ..usecases.run_verification import VerificationPipeline
from ...domain.entities.specification import Specification
from ...domain.specification_schema_v2 import load_acp_yaml_v2
from ...presentation.formatters.report_formatter import ReportFormatter
from ...domain.value_objects.verdict import Verdict
from .acp_conformity import summarize_acp_records


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _safe_ratio(n: int, d: int) -> float:
    return n / d if d else 0.0


class ACPBenchmarkRunner:
    def __init__(self, project_root: Path):
        self.project_root = Path(project_root).resolve()

    def run(
        self,
        manifest_path: Path,
        output_dir: Path,
        *,
        limit: Optional[int] = None,
        timeout_seconds: int = 120,
        persist_artifacts: bool = True,
        strict_contract: bool = True,
    ) -> Dict[str, Any]:
        manifest_path = self._resolve(manifest_path)
        output_dir = Path(output_dir).resolve()
        output_dir.mkdir(parents=True, exist_ok=True)
        cases_dir = output_dir / "cases"
        cases_dir.mkdir(parents=True, exist_ok=True)

        manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
        cases = list(manifest.get("cases", []))
        if limit is not None:
            cases = cases[: max(0, int(limit))]

        records: List[Dict[str, Any]] = []
        criterion_rows: List[Dict[str, Any]] = []
        for case in cases:
            record, criteria = self._run_case(
                case,
                cases_dir,
                timeout_seconds=timeout_seconds,
                persist_artifacts=persist_artifacts,
            )
            records.append(record)
            criterion_rows.extend(criteria)

        summary = summarize_acp_records(records, strict_contract=strict_contract).to_dict()
        summary["benchmark"] = manifest.get("benchmark", "AnalogCoder-Pro")
        summary["subset"] = manifest.get("subset", "ACP-28")
        summary["strict_contract"] = strict_contract
        summary["definition"] = {
            "simulation_success_rate": "simulation_success / circuits_total",
            "evaluation_rate": "(compliant + noncompliant) / circuits_total",
            "compliance_rate_evaluated": "compliant / evaluated",
            "noncompliance_rate_evaluated": "noncompliant / evaluated",
            "verified_compliance_yield": "compliant / circuits_total",
            "failure_to_evaluate_rate": "not_evaluated / circuits_total",
            "pass_rule": "PASS only when every mandatory ACP contract criterion is evaluated and passes",
            "fail_rule": "FAIL as soon as at least one mandatory ACP contract criterion is evaluated and fails",
            "not_evaluated_rule": "No demonstrated failure, but at least one mandatory criterion lacks valid evidence",
        }
        summary["contract_criteria"] = self._criterion_summary(criterion_rows)
        summary["coverage"] = self._coverage_summary(records, criterion_rows)
        # Canonical names used in the thesis/evaluation protocol.
        summary["Cov_circuits"] = summary["coverage"]["Cov_circuits"]
        summary["Cov_metrics"] = summary["coverage"]["Cov_metrics"]
        summary["Cov_analyses"] = summary["coverage"]["Cov_analyses"]
        summary["by_type"] = self._by_type(records)
        summary["runs_file"] = "runs.csv"
        summary["criteria_file"] = "criteria.csv"

        self._write_csv(output_dir / "runs.csv", records)
        self._write_csv(output_dir / "criteria.csv", criterion_rows)
        (output_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        (output_dir / "summary.md").write_text(self._summary_markdown(summary), encoding="utf-8")
        return summary

    def _run_case(self, case: Dict[str, Any], cases_dir: Path, *, timeout_seconds: int, persist_artifacts: bool):
        case_id = str(case["case_id"])
        spec_path = self._resolve(Path(case["spec"]))
        netlist_path = self._resolve(Path(case["netlist"]))
        case_dir = cases_dir / case_id
        case_dir.mkdir(parents=True, exist_ok=True)

        schema = load_acp_yaml_v2(spec_path)
        actual_hash = _sha256(netlist_path)
        expected_hashes = {str(case.get("netlist_sha256", "")).lower(), schema.provenance.dut.sha256.lower()}
        hash_ok = actual_hash.lower() in expected_hashes and len(expected_hashes) == 1

        base = {
            "case_id": case_id,
            "task_id": case.get("task_id"),
            "type": case.get("type"),
            "level": case.get("level"),
            "spec_path": str(spec_path.relative_to(self.project_root)),
            "netlist_path": str(netlist_path.relative_to(self.project_root)),
            "netlist_sha256": actual_hash,
            "dut_hash_ok": hash_ok,
            "mandatory_requirements": schema.mandatory_requirement_count,
            "implemented_mandatory_requirements": schema.executable_mandatory_requirement_count,
            "declared_contract_implementation_coverage": schema.contract_implementation_coverage,
        }
        if not hash_ok:
            record = {
                **base,
                "execution_status": "ERROR",
                "pipeline_compliance_status": "NOT_EVALUATED",
                "compliance_status": "NOT_EVALUATED",
                "contract_status": "NOT_EVALUATED",
                "contract_coverage": 0.0,
                "passed_mandatory_requirements": 0,
                "failed_mandatory_requirements": 0,
                "missing_mandatory_requirements": schema.mandatory_requirement_count,
                "simulation_success": False,
                "error": "DUT_HASH_MISMATCH",
            }
            return record, self._criteria_without_run(schema, case_id, "DUT_HASH_MISMATCH")

        specification = Specification.from_yaml(spec_path)
        pipeline = VerificationPipeline(
            use_llm=False,
            allow_mock=False,
            timeout_seconds=timeout_seconds,
            persist_artifacts=persist_artifacts,
        )
        report = pipeline.verify(specification, netlist_path, spec_path=spec_path)
        formatter = ReportFormatter(output_dir=case_dir)
        (case_dir / "verification_report.json").write_text(formatter.to_json(report, save=False), encoding="utf-8")

        result_by_name = {item.test_name: item for item in report.spec_results}
        criteria: List[Dict[str, Any]] = []
        passed = failed = missing = 0
        for requirement in schema.functional_requirements:
            if not requirement.mandatory:
                continue
            result = result_by_name.get(requirement.executable_metric or "") if requirement.implementation_status == "executable" else None
            if requirement.implementation_status != "executable":
                status = "NOT_IMPLEMENTED"
                missing += 1
                measured = None
            elif result is None or result.verdict == Verdict.ERROR or result.measured_value is None:
                status = "NOT_EVALUATED"
                missing += 1
                measured = None if result is None else result.measured_value
            elif result.verdict == Verdict.FAIL:
                status = "FAIL"
                failed += 1
                measured = result.measured_value
            elif result.verdict in {Verdict.PASS, Verdict.WARNING}:
                status = "PASS"
                passed += 1
                measured = result.measured_value
            else:
                status = "NOT_EVALUATED"
                missing += 1
                measured = result.measured_value
            criteria.append({
                "case_id": case_id,
                "requirement_id": requirement.id,
                "metric": requirement.metric,
                "executable_metric": requirement.executable_metric or "",
                "equivalence": requirement.equivalence,
                "implementation_status": requirement.implementation_status,
                "criterion_status": status,
                "measured_value": measured,
                "unit": requirement.unit,
                "operator": requirement.operator,
                "threshold": requirement.threshold,
                "minimum": requirement.minimum,
                "maximum": requirement.maximum,
                "analysis": requirement.analysis,
            })

        total = schema.mandatory_requirement_count
        evidence_count = passed + failed
        coverage = _safe_ratio(evidence_count, total)
        if report.execution_status.value != "SUCCESS":
            contract_status = "NOT_EVALUATED"
        elif failed:
            contract_status = "FAIL"
        elif missing:
            contract_status = "NOT_EVALUATED"
        elif total and passed == total:
            contract_status = "PASS"
        else:
            contract_status = "NOT_EVALUATED"

        record = {
            **base,
            "execution_status": report.execution_status.value,
            "simulation_success": bool(report.simulation_success),
            "pipeline_compliance_status": report.compliance_status.value,
            "compliance_status": contract_status,
            "contract_status": contract_status,
            "contract_coverage": coverage,
            "passed_mandatory_requirements": passed,
            "failed_mandatory_requirements": failed,
            "missing_mandatory_requirements": missing,
            "metric_count": len(report.spec_results),
            "missing_metrics": ";".join(report.missing_metrics),
            "failed_metrics": ";".join(report.failed_metric_names),
            "runtime_seconds": report.runtime_seconds,
            "ngspice_version": report.ngspice_version or "",
            "measurement_backend": report.measurement_backend or "",
            "scientifically_eligible": bool(report.scientifically_eligible),
            "error": "; ".join(report.errors or report.simulation_errors),
        }
        (case_dir / "contract_evidence.json").write_text(json.dumps({
            "record": record,
            "criteria": criteria,
            "policy": schema.verification.model_dump(),
        }, indent=2), encoding="utf-8")
        return record, criteria

    @staticmethod
    def _criteria_without_run(schema, case_id: str, reason: str):
        return [{
            "case_id": case_id, "requirement_id": r.id, "metric": r.metric,
            "executable_metric": r.executable_metric or "", "equivalence": r.equivalence,
            "implementation_status": r.implementation_status, "criterion_status": "NOT_EVALUATED",
            "measured_value": None, "unit": r.unit, "operator": r.operator,
            "threshold": r.threshold, "minimum": r.minimum, "maximum": r.maximum,
            "analysis": r.analysis, "reason": reason,
        } for r in schema.functional_requirements if r.mandatory]

    def _resolve(self, path: Path) -> Path:
        return path.resolve() if path.is_absolute() else (self.project_root / path).resolve()

    @staticmethod
    def _write_csv(path: Path, rows: List[Dict[str, Any]]):
        if not rows:
            path.write_text("", encoding="utf-8")
            return
        fields = []
        for row in rows:
            for key in row:
                if key not in fields:
                    fields.append(key)
        with path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader(); writer.writerows(rows)

    @staticmethod
    def _criterion_summary(rows: List[Dict[str, Any]]) -> Dict[str, Any]:
        total = len(rows)
        implemented = sum(r.get("implementation_status") == "executable" for r in rows)
        evaluated = sum(r.get("criterion_status") in {"PASS", "FAIL"} for r in rows)
        passed = sum(r.get("criterion_status") == "PASS" for r in rows)
        failed = sum(r.get("criterion_status") == "FAIL" for r in rows)
        return {
            "mandatory_total": total,
            "implemented": implemented,
            "evaluated": evaluated,
            "passed": passed,
            "failed": failed,
            "implementation_coverage": _safe_ratio(implemented, total),
            "runtime_evidence_coverage": _safe_ratio(evaluated, total),
        }

    @staticmethod
    def _coverage_summary(records: List[Dict[str, Any]], criteria: List[Dict[str, Any]]) -> Dict[str, Any]:
        circuit_ids = {str(r.get("case_id") or "") for r in records if r.get("case_id")}
        evaluated_circuit_ids = {
            str(r.get("case_id") or "")
            for r in criteria
            if r.get("case_id") and str(r.get("criterion_status") or "").upper() in {"PASS", "FAIL"}
        }
        mandatory_metrics = len(criteria)
        evaluated_metrics = sum(str(r.get("criterion_status") or "").upper() in {"PASS", "FAIL"} for r in criteria)
        requested_analyses = {str(r.get("analysis") or "").upper() for r in criteria if r.get("analysis")}
        executed_analyses = {
            str(r.get("analysis") or "").upper()
            for r in criteria
            if r.get("analysis") and str(r.get("criterion_status") or "").upper() in {"PASS", "FAIL"}
        }
        return {
            "Cov_circuits": _safe_ratio(len(evaluated_circuit_ids), len(circuit_ids)),
            "Cov_metrics": _safe_ratio(evaluated_metrics, mandatory_metrics),
            "Cov_analyses": _safe_ratio(len(executed_analyses), len(requested_analyses)),
            "circuits_total": len(circuit_ids),
            "circuits_with_runtime_evidence": len(evaluated_circuit_ids),
            "mandatory_metrics_total": mandatory_metrics,
            "mandatory_metrics_evaluated": evaluated_metrics,
            "analysis_types_requested": sorted(requested_analyses),
            "analysis_types_executed": sorted(executed_analyses),
        }

    @staticmethod
    def _by_type(records: List[Dict[str, Any]]) -> Dict[str, Any]:
        groups = defaultdict(list)
        for row in records:
            groups[str(row.get("type", "UNKNOWN"))].append(row)
        out = {}
        for key, rows in sorted(groups.items()):
            summary = summarize_acp_records(rows).to_dict()
            out[key] = summary
        return out

    @staticmethod
    def _summary_markdown(summary: Dict[str, Any]) -> str:
        pct = lambda x: f"{100.0*float(x):.2f}%"
        return "\n".join([
            "# ACP-28 deterministic compliance report",
            "",
            f"- Circuits: **{summary['circuits_total']}**",
            f"- Simulation SUCCESS: **{summary['simulation_success']}** ({pct(summary['simulation_success_rate'])})",
            f"- Evaluated against complete mandatory evidence: **{summary['evaluated']}** ({pct(summary['evaluation_rate'])})",
            f"- COMPLIANT: **{summary['compliant']}**",
            f"- NONCOMPLIANT: **{summary['noncompliant']}**",
            f"- NOT_EVALUATED: **{summary['not_evaluated']}**",
            f"- Compliance rate among evaluated circuits: **{pct(summary['compliance_rate_evaluated'])}**",
            f"- Non-compliance rate among evaluated circuits: **{pct(summary['noncompliance_rate_evaluated'])}**",
            f"- Verified Compliance Yield (COMPLIANT / all DUTs): **{pct(summary['verified_compliance_yield'])}**",
            f"- Contract completion rate: **{pct(summary['contract_completion_rate'])}**",
            f"- Cov_circuits: **{pct(summary['Cov_circuits'])}**",
            f"- Cov_metrics: **{pct(summary['Cov_metrics'])}**",
            f"- Cov_analyses: **{pct(summary['Cov_analyses'])}**",
            "",
            "PASS requires every mandatory ACP criterion to have valid evidence and pass. A single measured mandatory failure is enough for FAIL. Missing mandatory evidence never becomes PASS.",
        ]) + "\n"
